/* Energy CRM — ποιανού τα δεδομένα βλέπεις: δικά σου ή της ομάδας σου.
 *
 * Δεν είναι δικό της οθόνης. Ο διακόπτης «Δικά μου / Ομάδας» υπάρχει και στη
 * λίστα συμβάσεων και στις Εκκρεμότητες, και ΣΚΟΠΙΜΑ είναι ο ίδιος: όποιος
 * γυρίζει σε προβολή ομάδας για να δει τι τρέχει, δεν θέλει να το ξαναπεί
 * στην επόμενη οθόνη. Ήταν μία ιδιότητα του contractsState της λίστας — που
 * σήμαινε ότι οι Εκκρεμότητες διάβαζαν την κατάσταση άλλης οθόνης.
 *
 * Μεταφέροντας τη λίστα σε δικό της module, αυτό θα γινόταν κύκλος import.
 * Οπότε το μοναδικό κοινό κομμάτι κάθεται εδώ, όπως ο navigate: μια μονάδα
 * που δεν εισάγει τίποτα, ώστε να μπορούν να την εισάγουν όλοι.
 *
 * Δεν διατηρείται μεταξύ φορτώσεων σελίδας — και δεν πρέπει. Η προεπιλογή
 * «δικά μου» είναι η στενότερη προβολή· ένα αποθηκευμένο «ομάδας» θα έδειχνε
 * σε κάποιον δεδομένα συναδέλφων του χωρίς να το έχει ζητήσει σε αυτή τη
 * συνεδρία. */

var current = 'own';

/** @return {'own'|'team'} */
export function scope() {
	return current;
}

/**
 * Ό,τι δεν είναι ρητά «ομάδας» γίνεται «δικά μου».
 *
 * Η τιμή έρχεται από data-scope/data-pscope του DOM, δηλαδή από κάτι που
 * μπορεί να αλλάξει με ένα inspector. Η στενή προβολή είναι η ασφαλής
 * προεπιλογή· ο server ξανακρίνει ούτως ή άλλως, αλλά δεν στέλνουμε «team»
 * επειδή κάποιος έγραψε ό,τι να 'ναι στο attribute.
 */
export function setScope(next) {
	current = next === 'team' ? 'team' : 'own';
}
