<?php

/**
 * Το σχόλιο που στέλνει ο πάροχος μαζί με μια κατάσταση, σε μορφή που μπορεί
 * να μπει σε ιστορικό.
 *
 * ## Γιατί ζει εδώ και όχι στον εισαγωγέα Excel
 *
 * Γεννήθηκε στην (159) μέσα στην `ECRM_Import::apply()`, και ήταν λάθος που
 * παραδέχτηκα στην ίδια εγγραφή: το κόψιμο σε λογικό μήκος είναι **κανόνας
 * περιεχομένου**, όχι λεπτομέρεια ανάγνωσης υπολογιστικού φύλλου. Το
 * `HANDOVER.md` §1.12 το λέει ρητά — νέα λογική validation πάει στο `Domain`,
 * και ό,τι αγγίζεται σε legacy μετακομίζει όταν είναι φθηνό.
 *
 * Η απόδειξη ότι ανήκει εδώ ήρθε μία εγγραφή αργότερα: το ίδιο κόψιμο το
 * χρειάζεται και η διαδρομή που θα φέρνει καταστάσεις από API παρόχου (§1.13).
 * Δύο καλούντες, ένας κανόνας.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Providers\Domain;

final class ProviderNote
{
    /**
     * Πάνω από αυτό το μήκος το σχόλιο κόβεται.
     *
     * Απόφαση ιδιοκτήτη 27/08/2026: αρκεί για μια πρόταση αιτιολογίας, δεν
     * αφήνει ολόκληρη ελεύθερη στήλη να γεμίσει το ιστορικό της σύμβασης.
     */
    public const MAX_LENGTH = 300;

    private function __construct()
    {
    }

    /**
     * Το σχόλιο κομμένο σε λογικό μήκος, ή `null` όταν δεν υπάρχει.
     *
     * Το `null` και το κενό κείμενο είναι η ίδια απάντηση εδώ — «ο πάροχος δεν
     * είπε τίποτα» — και ο καλών δεν πρέπει να χρειάζεται να ξεχωρίζει κελί
     * που έλειπε από κελί με κενά μέσα.
     */
    public static function fromRaw(string $raw): ?string
    {
        $note = trim($raw);

        return $note === '' ? null : mb_substr($note, 0, self::MAX_LENGTH);
    }
}
