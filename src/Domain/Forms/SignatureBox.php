<?php

/**
 * Πού ακριβώς τυπώνεται η εικόνα μιας υπογραφής μέσα στη θέση της.
 *
 * ## Γιατί χρειάστηκε (288)
 *
 * Ως τώρα μια θέση υπογραφής ήταν `x, y, w` και το ύψος έβγαινε από την
 * αναλογία της εικόνας, με την εικόνα **κρεμασμένη από πάνω** (`y` = πάνω
 * άκρη). Το pad υπογραφής όμως έχει σταθερό ύψος (150px, 180px σε κινητό) και
 * πλάτος όσο η οθόνη: από υπολογιστή η εικόνα βγαίνει ~3,3:1, από κινητό
 * ~1,8:1. Με το ίδιο `w`, η υπογραφή κινητού έβγαινε σχεδόν διπλάσια σε ύψος
 * και κατέβαινε πάνω στο κείμενο από κάτω. Δηλαδή το πού «κάθεται» η υπογραφή
 * το αποφάσιζε η συσκευή του πελάτη, όχι ο χάρτης του εντύπου.
 *
 * ## Ο κανόνας
 *
 * Η θέση γίνεται **κουτί** `x, y, w, fit_h`. Η εικόνα χωράει μέσα του χωρίς
 * παραμόρφωση, **ακουμπά στην κάτω πλευρά** (εκεί είναι η γραμμή υπογραφής)
 * και στην αριστερή. Φαρδιά υπογραφή → πιάνει όλο το πλάτος και κάθεται στη
 * γραμμή. Ψηλή υπογραφή → μικραίνει ώσπου να χωρέσει στο ύψος, πάλι πάνω στη
 * γραμμή. Κανένα από τα δύο δεν βγαίνει ποτέ έξω από το κουτί.
 *
 * Θέση χωρίς `fit_h` κρατά ακριβώς την παλιά συμπεριφορά -- τα έντυπα των
 * άλλων παρόχων δεν αλλάζουν επειδή άλλαξαν της Protergia.
 *
 * Καθαρή κλάση, χωρίς WordPress: την καλεί το `ECRM_FormFill` και τη
 * δοκιμάζουν τα unit tests.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Forms;

final class SignatureBox
{
    private function __construct()
    {
    }

    /**
     * Η θέση και το μέγεθος (mm) της εικόνας για μια θέση υπογραφής.
     *
     * @param array<string, mixed> $slot   Η θέση όπως γράφεται στον χάρτη:
     *                                      page, x, y, w, h, και προαιρετικά fit_h.
     * @param int                  $pixelW Πλάτος της εικόνας σε pixel.
     * @param int                  $pixelH Ύψος της εικόνας σε pixel.
     *
     * @return array{x: float, y: float, w: float, h: float} Το `h` = 0 σημαίνει
     *         «από την αναλογία» -- ό,τι καταλαβαίνει και το `FPDF::Image()`.
     */
    public static function place(array $slot, int $pixelW, int $pixelH): array
    {
        $x = (float) ($slot['x'] ?? 0);
        $y = (float) ($slot['y'] ?? 0);
        $w = (float) ($slot['w'] ?? 40);
        $h = (float) ($slot['h'] ?? 0);

        $boxH = (float) ($slot['fit_h'] ?? 0);

        // Παλιά θέση, ή εικόνα που δεν διαβάστηκε: όπως πάντα.
        if ($boxH <= 0 || $pixelW <= 0 || $pixelH <= 0) {
            return ['x' => $x, 'y' => $y, 'w' => $w, 'h' => $h];
        }

        $h = $w * $pixelH / $pixelW;

        if ($h > $boxH) {
            $w = $boxH * $pixelW / $pixelH;
            $h = $boxH;
        }

        return ['x' => $x, 'y' => $y + $boxH - $h, 'w' => $w, 'h' => $h];
    }
}
