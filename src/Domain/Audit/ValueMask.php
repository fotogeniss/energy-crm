<?php

/**
 * Τι επιτρέπεται να γραφτεί σε ένα μήνυμα ελέγχου.
 *
 * Ο πίνακας `customers` κρατά έξι στήλες κρυπτογραφημένες
 * (`CustomerFields::ENCRYPTED`). Το ιστορικό ενεργειών όμως έγραφε την παλιά
 * και τη νέα τιμή τους σε **καθαρό κείμενο** μέσα στο `events.message`, οπότε
 * το `ECRM_ENCRYPT_PII` παρακαμπτόταν από την πλαϊνή πόρτα: ένα dump της βάσης
 * έδινε τα ΑΦΜ που η ίδια η βάση υποτίθεται ότι προστάτευε.
 *
 * Η λύση δεν είναι αφαίρεση. Το χρονολόγιο υπάρχει για να απαντά «ο πελάτης
 * λέει ότι δεν έδωσε ποτέ αυτό το ΑΦΜ — ποιος το άλλαξε και σε τι;», και ένα
 * «ΑΦΜ: ∅ → ∅» δεν απαντά τίποτα. Άρα μάσκα: αρκετό για να ξεχωρίσει η αλλαγή,
 * τίποτα που να ταυτοποιεί άνθρωπο.
 *
 * **Ο κανόνας για το ΠΟΙΑ πεδία, και γιατί σταματά εκεί:** μασκάρεται ό,τι
 * προστατεύει η βάση, τίποτα άλλο. Το `mobile` και το `last_name` κάθονται
 * καθαρά στον `customers` — μάσκα πάνω τους θα έκρυβε από τον πωλητή κάτι που
 * ένας κλέφτης θα έπαιρνε ούτως ή άλλως από τη διπλανή στήλη. Θόρυβος χωρίς
 * κέρδος. Αν κάποτε μπει στήλη στο `CustomerFields::ENCRYPTED`, μπαίνει και
 * εδώ — οι δύο λίστες πρέπει να λένε το ίδιο πράγμα.
 *
 * **Τρεις συμπεριφορές, όχι μία, και ο λόγος είναι μετρημένος:**
 *
 * - `TAIL` (ΑΦΜ, ΑΔΤ, τηλέφωνο): τα τρία τελευταία ψηφία. Ξεχωρίζουν την
 *   αλλαγή από τη μη-αλλαγή χωρίς να ταυτοποιούν.
 * - `HEAD` (ΤΚ): τα τρία **πρώτα**. Σε ελληνικό ΤΚ τα πρώτα τρία είναι η
 *   περιοχή — χρήσιμη στο ιστορικό, ακίνδυνη· τα δύο τελευταία είναι το
 *   τετράγωνο, δηλαδή ακριβώς το κομμάτι που εντοπίζει σπίτι. Ο ίδιος κανόνας
 *   με τα υπόλοιπα θα κρατούσε λάθος μισό.
 * - `OPAQUE` (οδός, αριθμός): καμία τιμή. Το «42» δεν χωρά μάσκα, και το
 *   «••••••ίας» πάνω στην «Ακαδημίας» είναι κατάληξη, όχι πληροφορία. Όταν
 *   κάθε μερική εκδοχή είτε λέει πολλά είτε τίποτα, η ειλικρινής απάντηση
 *   είναι σκέτο «άλλαξε».
 *
 * Καθαρό PHP: καμία κλήση πλατφόρμας, καμία σύνδεση με τη βάση, καμία γνώση
 * του πού καταλήγει το κείμενο. Δοκιμάζεται χωρίς βάση.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Audit;

final class ValueMask
{
    /** Πόσοι χαρακτήρες επιβιώνουν όταν επιβιώνει κάτι. */
    public const KEEP = 3;

    /** Ο χαρακτήρας της μάσκας. Ένα σύμβολο, όχι αστερίσκος: δεν μοιάζει με τιμή. */
    private const DOT = '•';

    /** Το κείμενο που αντικαθιστά ολόκληρο το «παλιά → νέα» στα αδιαφανή πεδία. */
    public const CHANGED = 'άλλαξε';

    /** Κρατούν τους τελευταίους KEEP χαρακτήρες. */
    private const TAIL = ['afm', 'adt', 'phone'];

    /** Κρατούν τους πρώτους KEEP χαρακτήρες. */
    private const HEAD = ['postal_code'];

    /** Δεν δείχνουν καμία τιμή, ούτε μασκαρισμένη. */
    private const OPAQUE = ['street', 'street_no'];

    private function __construct()
    {
    }

    /**
     * Τα πεδία που αυτή η κλάση αγγίζει με οποιονδήποτε τρόπο.
     *
     * Εκτεθειμένο αντί για αντιγραμμένο, για τον ίδιο λόγο που το κάνει η
     * `CustomerFields::encryptedColumns()`: μια δεύτερη λίστα αλλού θα
     * συμφωνούσε σήμερα και θα απέκλινε την πρώτη φορά που προστίθεται πεδίο.
     *
     * @return list<string>
     */
    public static function fields(): array
    {
        return array_merge(self::TAIL, self::HEAD, self::OPAQUE);
    }

    /** Αν αυτό το πεδίο δεν επιτρέπεται να δείξει καμία τιμή. */
    public static function isOpaque(string $field): bool
    {
        return in_array($field, self::OPAQUE, true);
    }

    /**
     * Η τιμή όπως επιτρέπεται να γραφτεί.
     *
     * Πεδίο εκτός των λιστών επιστρέφεται αυτούσιο — η κλάση δεν έχει άποψη
     * για ό,τι η βάση δεν προστατεύει.
     *
     * Το κενό μένει κενό: ο καλών το μετατρέπει σε «∅», και μια μάσκα πάνω
     * στο τίποτα θα ισχυριζόταν τιμή που δεν υπάρχει.
     *
     * Τιμή μέχρι KEEP χαρακτήρες καλύπτεται **ολόκληρη**. Το να «κρατήσεις τα
     * τρία τελευταία» ενός τριψήφιου είναι να μην κρατήσεις μάσκα καθόλου.
     */
    public static function apply(string $field, string $value): string
    {
        if (self::isOpaque($field)) {
            return self::CHANGED;
        }

        $trimmed = trim($value);

        if ($trimmed === '') {
            return '';
        }

        $tail = in_array($field, self::TAIL, true);
        $head = in_array($field, self::HEAD, true);

        if (! $tail && ! $head) {
            return $value;
        }

        $length = mb_strlen($trimmed, 'UTF-8');

        if ($length <= self::KEEP) {
            return str_repeat(self::DOT, $length);
        }

        $dots = str_repeat(self::DOT, $length - self::KEEP);

        return $tail
            ? $dots . mb_substr($trimmed, -self::KEEP, null, 'UTF-8')
            : mb_substr($trimmed, 0, self::KEEP, 'UTF-8') . $dots;
    }
}
