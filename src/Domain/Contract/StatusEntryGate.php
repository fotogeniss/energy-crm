<?php

/**
 * Τι απαιτεί μια σύμβαση **πριν** μπει σε μια κατάσταση.
 *
 * Ο `ContractStatus` ξέρει ποια μετάβαση είναι νόμιμη· δεν ξέρει τίποτα για τη
 * συγκεκριμένη σύμβαση. Ο `CancellationGate` έλυσε ακριβώς αυτό για την
 * ακύρωση, με αντικείμενο που ρωτάει ο `ContractLifecycle`. Αυτή η διεπαφή
 * είναι το ίδιο σχήμα για την **είσοδο** σε μια κατάσταση: «επιτρέπεται αυτή η
 * σύμβαση να γίνει Ενεργή;» -- ερώτηση που θέλει χαρτιά, υπογραφή, δεδομένα.
 *
 * ## Γιατί διεπαφή και όχι σκέτη κλάση
 *
 * Η μόνη σημερινή υλοποίηση (`Infrastructure\PaperworkGate`) καλεί
 * `ECRM_Docs`, δηλαδή WordPress. Ο `ContractLifecycle` ζει στο `Domain` και
 * δεν επιτρέπεται να το ξέρει αυτό (`DomainStaysFrameworkFreeTest`· ο
 * `RejectionFollowUp` έμαθε το ίδιο μάθημα στις 31/08 και μετακόμισε στο
 * `Infrastructure`). Η διεπαφή κρατά το βέλος να δείχνει προς τα μέσα: το
 * Domain ορίζει τι χρειάζεται, το Infrastructure το παρέχει.
 *
 * Δεύτερο κέρδος, όχι δευτερεύον: ο lifecycle γίνεται unit-testable με ένα
 * τριών γραμμών test double, χωρίς βάση και χωρίς αρχεία.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Contract;

interface StatusEntryGate
{
    /**
     * Άρνηση της εισόδου σε αυτή την κατάσταση, ή null για να προχωρήσει.
     *
     * Δέχεται μόνο τον **στόχο**, όχι την προέλευση: η ερώτηση «είναι έτοιμη
     * αυτή η σύμβαση να γίνει Χ;» έχει την ίδια απάντηση όποια κι αν είναι η
     * σημερινή της κατάσταση -- και έτσι η ίδια πύλη απαντά και στη
     * **δημιουργία**, όπου προέλευση δεν υπάρχει καθόλου.
     */
    public function refusalOnEntry(ContractStatus $target, int $contractId): ?string;
}
