<?php

/**
 * Το κλειδί που κάνει μια «δημιουργία σύμβασης» να μετρήσει μία φορά.
 *
 * ## Το πρόβλημα που λύνει
 *
 * Το `POST /contracts` με `contract_id === 0` δημιουργεί. Δύο φορές το ίδιο
 * αίτημα -- διπλό tap σε αργή σύνδεση, retry μετά από timeout, και αύριο η
 * ουρά του (Δ) -- δημιουργούσε δύο συμβάσεις και, χειρότερα, δύο πελάτες:
 * ο πελάτης γράφεται ΠΡΙΝ τη σύμβαση στη ροή του ContractSaveController.
 *
 * Ο client παράγει ένα uuid v4 ανά «πρόθεση δημιουργίας» και το ξαναστέλνει
 * αυτούσιο σε κάθε επανάληψη του ίδιου αιτήματος. Το κλειδί δεν λέει «αυτό
 * είναι το ίδιο περιεχόμενο»· λέει «αυτή είναι η ίδια πρόθεση».
 *
 * ## Γιατί αυστηρά uuid v4 και όχι οποιαδήποτε συμβολοσειρά
 *
 * Το κλειδί μπαίνει σε UNIQUE ευρετήριο μαζί με τον χρήστη. Ενα ελεύθερο
 * αλφαριθμητικό από τον client θα ήταν επιφάνεια για σκόπιμη σύγκρουση
 * (στέλνω το κλειδί σου, δεσμεύω τη θέση σου) και για ατέρμονο μήκος. Η
 * μορφή v4 δίνει 122 τυχαία bits -- η σύγκρουση κατά λάθος είναι αδύνατη,
 * και η σύγκρουση επίτηδες δεν βοηθά κανέναν επειδή το ευρετήριο περιέχει
 * ΚΑΙ το `partner_user_id`: το κλειδί ενός συνεργάτη δεν αγγίζει ποτέ άλλον.
 *
 * ## Τι ΔΕΝ κάνει
 *
 * Δεν αφορά ενημέρωση (`contract_id > 0`). Μια ενημέρωση γράφει σε
 * συγκεκριμένη γραμμή, και η διπλή μετάβαση κόβεται ήδη -- ο γράφος του
 * `ContractStatus` δεν έχει self-loops και το `ContractLifecycle::moveTo()`
 * επιστρέφει νωρίς όταν το `from` ισούται με το `to`.
 *
 * Καθαρό PHP, μηδέν WordPress: μεταφέρεται αυτούσιο (§1.12).
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Contract;

final class RequestKey
{
    /** Το μήκος ενός uuid με τις παύλες -- και το μήκος της στήλης. */
    public const LENGTH = 36;

    /**
     * Η μορφή, γραμμένη μία φορά.
     *
     * Το `4` στην τρίτη ομάδα και το `[89ab]` στην τέταρτη είναι η έκδοση και
     * η παραλλαγή του v4. Ελέγχονται επίτηδες: ένα uuid v1 κουβαλά τη MAC
     * διεύθυνση και τη χρονική στιγμή της συσκευής, που δεν έχουν καμία δουλειά
     * να ταξιδεύουν ως ταυτότητα αιτήματος.
     */
    private const SHAPE = '/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/';

    private function __construct()
    {
    }

    /** Πεζά και χωρίς κενά -- η μοναδική γραφή που φτάνει στη βάση. */
    public static function normalise(string $key): string
    {
        return strtolower(trim($key));
    }

    /** Είναι uuid v4; Δέχεται ό,τι θα δεχόταν και το `normalise()`. */
    public static function isValid(string $key): bool
    {
        return preg_match(self::SHAPE, self::normalise($key)) === 1;
    }
}
