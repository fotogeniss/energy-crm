<?php

/**
 * Μια σύμβαση που υπήρξε ενεργή δεν ακυρώνεται· τερματίζεται.
 *
 * Οι δύο τερματικές καταστάσεις δεν είναι συνώνυμες. «Ακυρώθηκε» σημαίνει ότι η
 * αίτηση δεν έγινε ποτέ παροχή. «Τερματίστηκε» σημαίνει ότι έγινε και μετά
 * σταμάτησε. Η διαφορά είναι εμπορική, όχι διακοσμητική: στη μία περίπτωση δεν
 * υπήρξε ποτέ τζίρος, στην άλλη υπήρξε και κάποιος πληρώθηκε γι' αυτόν.
 *
 * ## Γιατί δεν αρκεί ο γράφος
 *
 * Το `ContractStatus::allowedNext()` δεν έχει `Cancelled` κάτω από την `Active`,
 * και μέχρι σήμερα αυτό θεωρούνταν ο κανόνας. Δεν ήταν: η `Pending` δέχεται
 * `Cancelled`, και η `Active` πάει στην `Pending`. Δύο κλικ αντί για ένα, ίδιο
 * αποτέλεσμα. Ο έλεγχος της 18/08/2026 το κατέγραψε ως 20.6 — «ο κανόνας δεν
 * επιβάλλει τίποτα, απλώς απαιτεί δύο βήματα».
 *
 * Το κενό δεν κλείνει μέσα στον enum, και αυτό είναι σωστό. Η `Pending` δέχεται
 * συμβάσεις και από τη `Submitted`, όπου η ακύρωση είναι απολύτως λογική, και
 * από την `Active`, όπου δεν είναι — και δεν θυμάται από πού ήρθε. Ο enum είναι
 * καθαρή λογική χωρίς βάση δεδομένων, επίτηδες. Η μνήμη υπάρχει αλλού: στο
 * ιστορικό, όπου κάθε `moveTo()` αφήνει `status_change` με `to_status`.
 *
 * Άρα ο κανόνας θέλει ένα γεγονός που ο γράφος δεν μπορεί να ξέρει, και γίνεται
 * αντικείμενο που το ρωτάνε όσοι μετακινούν — όχι `if` αντιγραμμένο σε τέσσερις
 * διαδρομές. Ίδιο σχήμα με το `DraftExitGate`, για τον ίδιο λόγο.
 *
 * ## Ο κανόνας ισχύει από τη μετάβαση και μετά, και αυτό αρκεί
 *
 * Η πύλη βλέπει μόνο ό,τι έχει γραφτεί ως `status_change`. Σύμβαση που θα είχε
 * γίνει ενεργή χωρίς τέτοια εγγραφή θα διάβαζε ως «δεν υπήρξε ποτέ ενεργή».
 *
 * Δεν είναι κενό που πρέπει να κλείσει. Ο ιδιοκτήτης το έθεσε ρητά στις
 * 18/08/2026: το τοπικό site **είναι** η μελλοντική παραγωγή, τα σημερινά
 * δεδομένα είναι δοκιμαστικά και σβήνονται πριν ανέβει, και αυτό που μετράει
 * είναι «από εδώ και πέρα μια ενεργή σύμβαση να μην ακυρώνεται έτσι απλά».
 * Κάθε ενεργοποίηση από το go-live και μετά περνά από τον `ContractLifecycle`
 * και αφήνει το γεγονός της — ο δρόμος της εισαγωγής Excel μπήκε κι αυτός εκεί
 * με το εύρημα 7. Δηλαδή δεν πρόκειται να υπάρξει σύμβαση χωρίς ιστορικό.
 *
 * Γι' αυτό δεν αντισταθμίζεται με μαντεψιά πάνω στο `start_date`: η κατάσταση
 * της σύμβασης είναι δεδομένο, η ημερομηνία έναρξης είναι πρόθεση, και μια
 * εικασία θα ήταν χειρότερη από το να μην κοιτάξουμε καθόλου.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Contract;

use EnergyCRM\Persistence\EventRepository;
use EnergyCRM\Persistence\PayoutRepository;

final class CancellationGate
{
    /** Το ίδιο μήνυμα από κάθε πόρτα, γιατί είναι το ίδιο γεγονός. */
    public const WAS_ACTIVE = 'Η σύμβαση υπήρξε ενεργή, οπότε δεν ακυρώνεται. '
        . 'Αν η παροχή σταμάτησε, χρησιμοποίησε «Έκλεισε».';

    /**
     * Εύρημα ελέγχου ασφαλείας/λογικής #2 (26/08/2026): το `isPayable()`
     * περιλαμβάνει `Routed`/`Resolved`, όχι μόνο `Active` -- μια σύμβαση
     * μπορεί να μπει σε παρτίδα και να πληρωθεί ΠΡΙΝ γίνει ποτέ Ενεργή. Ο
     * ιδιοκτήτης επέλεξε ρητά το ίδιο μπλοκάρισμα με το `WAS_ACTIVE` παρακάτω
     * αντί για σιωπηλή αποδοχή.
     */
    public const WAS_PAID = 'Η σύμβαση έχει ήδη μπει σε πληρωμένη παρτίδα εκκαθάρισης, οπότε δεν ακυρώνεται. '
        . 'Διευθέτησε πρώτα την προμήθεια, μετά χρησιμοποίησε «Έκλεισε».';

    public function __construct(
        private readonly EventRepository $events,
        private readonly PayoutRepository $payouts,
    ) {
    }

    /**
     * Άρνηση της μετάβασης, ή null για να προχωρήσει.
     *
     * Η ερώτηση στη βάση γίνεται μόνο όταν ο στόχος είναι η ακύρωση. Κάθε άλλη
     * μετάβαση φεύγει από την πρώτη γραμμή χωρίς ερώτημα — ο κανόνας δεν έχει
     * λόγο να κοστίζει σε διαδρομές που δεν αφορά.
     *
     * Το `$from` ελέγχεται πρώτο και χωρίς ιστορικό: σύμβαση που είναι **τώρα**
     * ενεργή δεν χρειάζεται απόδειξη ότι υπήρξε. Ο γράφος το απαγορεύει ήδη,
     * αλλά μια πύλη που στηρίζεται σε άλλον για τη μισή της δουλειά είναι
     * ακριβώς το σχήμα που κλείνει εδώ.
     */
    public function refusalOnMove(ContractStatus $from, ContractStatus $target, int $contractId): ?string
    {
        if ($target !== ContractStatus::Cancelled) {
            return null;
        }

        if ($from === ContractStatus::Active) {
            return self::WAS_ACTIVE;
        }

        if ($this->events->hasReached($contractId, ContractStatus::Active->value)) {
            return self::WAS_ACTIVE;
        }

        return $this->payouts->isPartOfPaidBatch($contractId) ? self::WAS_PAID : null;
    }
}
