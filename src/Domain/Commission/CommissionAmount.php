<?php

/**
 * Πόσο μετράει μια σύμβαση: το στιγμιότυπο αν σφραγίστηκε, αλλιώς ο ζωντανός
 * υπολογισμός.
 *
 * Ο ιδιοκτήτης αποφάσισε 18/08/2026 ότι η εκκαθάριση είναι στιγμιότυπο:
 * πληρωμένη παρτίδα δεν αλλάζει αναδρομικά επειδή άλλαξε αργότερα κανόνας
 * προμήθειας. Την ίδια μέρα η απόφαση γράφτηκε σε **τρία** σημεία — οθόνη
 * προμηθειών, βεβαίωση PDF, ακύρωση παρτίδας — και το επόμενο πρωί ο έλεγχος
 * λειτουργίας βρήκε **τέταρτο** που δεν την τηρούσε: η κατάταξη της ομάδας
 * υπολόγιζε ζωντανά ό,τι είχε ήδη πληρωθεί.
 *
 * Τέσσερα σημεία που παίρνουν την ίδια απόφαση είναι ο ορισμός του κανόνα που
 * πρέπει να γίνει αντικείμενο. Το τέταρτο δεν το βρήκε καμία αναζήτηση για
 * `payout_amount` — δεν το ανέφερε καν· το βρήκε το να ρωτήσω «ποιος αλλού
 * μετράει λεφτά».
 *
 * ## Γιατί ο ζωντανός υπολογισμός δίνεται απ' έξω
 *
 * Ο κανόνας εδώ είναι δύο γραμμές και είναι καθαρή λογική. Ο υπολογισμός δεν
 * είναι: ζει στην `ECRM_Commissions::amount_for()`, θέλει τους ενεργούς κανόνες
 * από τη βάση, και είναι legacy κλάση που το phpstan μόνο σαρώνει. Αν την
 * καλούσε αυτό το αρχείο, θα κουβαλούσε βάση και WordPress μαζί του και θα
 * έπαυε να δοκιμάζεται με σκέτο unit test — ακριβώς ό,τι κέρδισε ο `RuleMatch`
 * όταν βγήκε από εκεί.
 *
 * Έτσι ο καλών δίνει τον υπολογισμό (`[ECRM_Commissions::class, 'amount_for']`)
 * και **δεν εκτελείται καθόλου** όταν υπάρχει στιγμιότυπο. Δεν είναι μόνο
 * οικονομία: υπολογισμός που γίνεται και πετιέται είναι ο τρόπος να μπει
 * αργότερα μια παρενέργεια σε δρόμο που υποτίθεται ότι δεν περπατιέται.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Commission;

final class CommissionAmount
{
    private function __construct()
    {
    }

    /**
     * Το ποσό της σύμβασης.
     *
     * `payout_amount` NULL ή απόν σημαίνει «χωρίς στιγμιότυπο»: είτε δεν έχει
     * μπει σε παρτίδα, είτε μπήκε πριν αρχίσει να κρατιέται (μετάβαση 0016).
     * Και στις δύο περιπτώσεις ο ζωντανός υπολογισμός είναι η σωστή απάντηση,
     * και είναι και η μόνη που υπήρχε ποτέ.
     *
     * @param array<string, mixed> $row      Γραμμή σύμβασης· διαβάζεται μόνο το `payout_amount`.
     * @param callable(array<string, mixed>): float $live Ο υπολογισμός, όταν χρειαστεί.
     */
    public static function of(array $row, callable $live): float
    {
        $snapshot = $row['payout_amount'] ?? null;

        return $snapshot === null ? (float) $live($row) : (float) $snapshot;
    }
}
