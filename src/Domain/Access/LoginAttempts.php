<?php

/**
 * Ποτε μια σειρα αποτυχημενων συνδεσεων γινεται κλειδωμα, και για ποσο.
 *
 * Το WordPress δεν μετραει αποτυχημενες συνδεσεις και δεν τις σταματαει ποτε:
 * ο ιδιος κωδικος μπορει να δοκιμαστει οσες φορες θελει κανεις, με ολο το
 * κοστος του ελεγχου κωδικου να το πληρωνει ο server. Πισω απο αυτη τη
 * συνδεση καθονται ΑΦΜ, ΑΔΤ και σαρωμενες ταυτοτητες πελατων.
 *
 * ## Γιατι δυο μετρητες και οχι ενας
 *
 * Ενας μετρητης ανα IP σταματαει το σαρωμα πολλων λογαριασμων απο ενα
 * μηχανημα, αλλα οχι την επιθεση που δοκιμαζει εναν λογαριασμο απο εκατο
 * διαφορετικες διευθυνσεις. Ενας μετρητης ανα ονομα χρηστη κανει το
 * αντιστροφο. Οι δυο μαζι καλυπτουν και τις δυο μορφες, και το οριο τους
 * ειναι διαφορετικο επιτηδες: το ονομα χρηστη ειναι το στενο μονοπατι (8),
 * η IP το πλατυ (20).
 *
 * ## Γιατι εδω και οχι μεσα στα hooks
 *
 * Η αποθηκευση των μετρησεων ειναι δουλεια της πλατφορμας -- transients
 * σημερα, Redis η πινακας αυριο. Η **αποφαση** ομως («εχει φτασει το οριο;
 * ποσο ακομα;») ειναι καθαρος υπολογισμος, και εδω τρεχει σε unit test χωρις
 * WordPress (§1.12). Το Access\LoginThrottle κανει μονο το διαβασμα και το
 * γραψιμο.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Access;

final class LoginAttempts
{
    /**
     * Ποσες αποτυχιες αντεχει ενα ονομα χρηστη μεσα στο παραθυρο.
     *
     * Οκτω, οχι τρεις: ο συνεργατης που δοκιμαζει τρεις-τεσσερις παραλλαγες
     * του κωδικου του πριν τον θυμηθει δεν πρεπει να το συναντησει ποτε. Ο
     * επιτιθεμενος το συναντα στην ογδοη, που ειναι πολυ πριν χρησιμευσει σε
     * οτιδηποτε.
     */
    public const PER_USER = 8;

    /**
     * Ποσες αποτυχιες αντεχει μια διευθυνση μεσα στο ιδιο παραθυρο.
     *
     * Πιο χαλαρο απο το ονομα χρηστη γιατι μια διευθυνση μπορει να ειναι
     * νομιμα κοινη: γραφειο με ενα NAT, η -- χειροτερα -- ολοκληρο το site
     * πισω απο proxy που κανεις δεν δηλωσε στο ecrm_trusted_proxies, οποτε
     * ολοι οι επισκεπτες μοιαζουν ενας. Ο RequestIp το προειδοποιει ηδη· εδω
     * το τιμαμε αφηνοντας το πλατυ μονοπατι πλατυ.
     */
    public const PER_IP = 20;

    /** Το παραθυρο μετρησης, και ταυτοχρονα η διαρκεια του κλειδωματος. */
    public const WINDOW = 900;

    private function __construct()
    {
    }

    /** Εχει φτασει ενας μετρητης το οριο του; */
    public static function locked(int $failures, int $limit): bool
    {
        return $limit > 0 && $failures >= $limit;
    }

    /**
     * Ποσα δευτερολεπτα μενουν μεχρι να ανοιξει ξανα το παραθυρο.
     *
     * Ποτε αρνητικο: ενα παραθυρο που εληξε ειναι μηδεν, οχι χρεος.
     */
    public static function secondsLeft(int $windowEndsAt, int $now): int
    {
        return max(0, $windowEndsAt - $now);
    }

    /**
     * Η τελικη απαντηση: ποσο πρεπει να περιμενει ο καλων, 0 = ελευθερος.
     *
     * Οταν κλειδωνουν και οι δυο μετρητες, μετραει ο μεγαλυτερος -- το να
     * ανοιξει ο ενας δεν σημαινει τιποτα οσο ο αλλος ειναι κλειστος, και μια
     * μικροτερη υποσχεση («δοκιμασε σε 2 λεπτα») που δεν τηρειται ειναι
     * χειροτερη απο καμια.
     *
     * @param list<array{int, int, int}> $buckets Τριαδες [αποτυχιες, οριο, ληξη].
     */
    public static function waitSeconds(array $buckets, int $now): int
    {
        $wait = 0;

        foreach ($buckets as [$failures, $limit, $endsAt]) {
            if (! self::locked($failures, $limit)) {
                continue;
            }

            $wait = max($wait, self::secondsLeft($endsAt, $now));
        }

        return $wait;
    }

    /**
     * Πως το λεμε στον ανθρωπο που το βλεπει.
     *
     * Λεπτα, στρογγυλεμενα προς τα πανω: «σε 1 λεπτο» οταν μενουν 30
     * δευτερολεπτα ειναι μικρη υπερβολη, ενω «σε 0 λεπτα» ειναι λαθος.
     */
    public static function waitPhrase(int $seconds): string
    {
        if ($seconds <= 0) {
            return 'σε λίγο';
        }

        $minutes = (int) ceil($seconds / 60);

        return $minutes === 1 ? 'σε 1 λεπτό' : "σε {$minutes} λεπτά";
    }
}
