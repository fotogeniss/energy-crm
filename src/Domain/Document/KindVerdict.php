<?php

/**
 * Η απόφαση: τι κάνουμε όταν η ανάγνωση ενός εγγράφου διαφωνεί με την ετικέτα
 * που του έβαλε ο συνεργάτης.
 *
 * ## Το πρόβλημα που λύνει
 *
 * Το widget ανεβάσματος έστελνε ΜΙΑ τιμή είδους για ΟΛΑ τα αρχεία ενός batch.
 * Ταυτότητα και λογαριασμός μαζί σήμαινε ότι το ένα από τα δύο έπαιρνε λάθος
 * ετικέτα, και τότε το `ECRM_Docs::checklist()` -- που ελέγχει ΠΑΡΟΥΣΙΑ ενός
 * `doc_kind` -- έλεγε «λείπουν δικαιολογητικά» για χαρτί που ήταν ήδη εκεί.
 * Το ανέβασμα ανά αρχείο λύνει την αιτία· αυτή η κλάση καλύπτει το ανθρώπινο
 * λάθος που θα ξανασυμβεί ούτως ή άλλως.
 *
 * ## Γιατί εδώ, χωρίς WordPress
 *
 * Ολόκληρη η απόφαση είναι τρεις συγκρίσεις πάνω σε strings. Δεν χρειάζεται
 * βάση, δεν χρειάζεται hook, και είναι ακριβώς το είδος λογικής που πρέπει να
 * μπορεί να δοκιμαστεί χωρίς να σηκωθεί WordPress (§1.12). Ο κώδικας που
 * ΕΦΑΡΜΟΖΕΙ την απόφαση ζει στο `Infrastructure\DocumentKindReview`.
 *
 * @package EnergyCRM
 */

declare(strict_types=1);

namespace EnergyCRM\Domain\Document;

final class KindVerdict
{
    /**
     * Τα είδη που η ανάγνωση ξέρει να αναγνωρίσει.
     *
     * Είναι τα ίδια τρία που ήδη περιγράφει το prompt του εξαγωγέα -- ταυτότητα,
     * λογαριασμός παρόχου, κάρτα SIM. Ο,τι άλλο κρέμεται σε μια αίτηση
     * (εξουσιοδότηση, Ε9, πιστοποιητικό) δεν έχει σταθερή οπτική υπογραφή που
     * να αναγνωρίζεται με σιγουριά, και μια λάθος αυτόματη διόρθωση εκεί θα
     * ήταν χειρότερη από καμία.
     *
     * @var list<string>
     */
    public const DETECTABLE = ['id_card', 'provider_bill', 'sim_card'];

    /** Η ετικέτα άλλαξε αυτόματα, μετά από ανάγνωση. */
    public const SOURCE_AI = 'ai';

    /** Η ανάγνωση έγινε και συμφώνησε -- τίποτα δεν άλλαξε, μη ξανακοιτάς. */
    public const SOURCE_AI_OK = 'ai_ok';

    /**
     * Αποφάσισε άνθρωπος. Κλειδωμένο.
     *
     * Μπαίνει όταν ο συνεργάτης πατήσει «Αναίρεση». Χωρίς αυτό, η επόμενη
     * ανάγνωση θα ξανα-άλλαζε ακριβώς ό,τι μόλις ανέτρεψε -- και ο συνεργάτης
     * θα έβλεπε την επιλογή του να γυρίζει πίσω χωρίς εξήγηση.
     */
    public const SOURCE_HUMAN = 'human';

    /** Πόσο σίγουρη πρέπει να είναι η ανάγνωση για να αλλάξει ετικέτα. */
    public const CONFIDENCE_REQUIRED = 'high';

    /**
     * Πρέπει να διαβαστεί αυτό το αρχείο;
     *
     * Μόνο όσα δεν έχουν κριθεί ποτέ. Ενα αρχείο που διαβάστηκε -- είτε
     * διορθώθηκε είτε συμφώνησε -- δεν ξαναδιαβάζεται: η δεύτερη ανάγνωση θα
     * έδινε την ίδια απάντηση και θα πλήρωνε δεύτερη φορά, σε ΚΑΘΕ άνοιγμα της
     * καρτέλας, για πάντα.
     */
    public static function shouldExamine(?string $source): bool
    {
        return $source === null || $source === '';
    }

    /** Κλειδωμένο από άνθρωπο -- καμία αυτόματη αλλαγή, ποτέ. */
    public static function isLocked(?string $source): bool
    {
        return $source === self::SOURCE_HUMAN;
    }

    /** Η ετικέτα άλλαξε αυτόματα και μπορεί να αναιρεθεί. */
    public static function isAutoCorrected(?string $source): bool
    {
        return $source === self::SOURCE_AI;
    }

    /**
     * Η νέα ετικέτα, ή null αν δεν αλλάζει τίποτα.
     *
     * Τέσσερις λόγοι να μην αλλάξει τίποτα, και όλοι είναι σιωπηλοί -- ο
     * συνεργάτης δεν χρειάζεται να μάθει ότι έγινε μια ανάγνωση που δεν
     * κατέληξε κάπου:
     *
     * 1. Η ανάγνωση δεν κατάλαβε τι είναι (`null` ή κενό).
     * 2. Κατάλαβε κάτι εκτός των `DETECTABLE` -- κυρίως «άλλο έγγραφο». Μια
     *    διόρθωση ΠΡΟΣ το «άλλο» δεν κερδίζει τίποτα: δεν ικανοποιεί κανένα
     *    απαιτούμενο δικαιολογητικό, και θα κατέστρεφε μια σωστή χειροκίνητη
     *    επιλογή που απλώς δεν αναγνωρίζεται οπτικά.
     * 3. Δεν είναι σίγουρη. Το κατώφλι είναι ρητό και ένα: `high`. Με
     *    οτιδήποτε χαμηλότερο, η επιλογή του ανθρώπου στέκει.
     * 4. Συμφωνεί ήδη με αυτό που διάλεξε ο συνεργάτης.
     */
    public static function correction(
        string $declared,
        ?string $detected,
        ?string $confidence
    ): ?string {
        $detected = $detected === null ? '' : trim($detected);

        if ($detected === '' || ! in_array($detected, self::DETECTABLE, true)) {
            return null;
        }

        if (trim((string) $confidence) !== self::CONFIDENCE_REQUIRED) {
            return null;
        }

        if ($detected === trim($declared)) {
            return null;
        }

        return $detected;
    }

    /**
     * Η πηγή που γράφεται μετά από μια ανάγνωση.
     *
     * Ξεχωριστή από την `correction()` επειδή απαντά σε άλλο ερώτημα: εκείνη
     * λέει «τι ετικέτα», αυτή λέει «να ξανακοιτάξω ποτέ». Ακόμα και όταν δεν
     * αλλάζει τίποτα, το αρχείο σημειώνεται ως διαβασμένο -- αλλιώς κάθε
     * άνοιγμα της καρτέλας θα ξεκινούσε την ίδια ανάγνωση από την αρχή.
     */
    public static function sourceAfterReview(?string $correction): string
    {
        return $correction === null ? self::SOURCE_AI_OK : self::SOURCE_AI;
    }
}
